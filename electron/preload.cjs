const {contextBridge, ipcRenderer, webFrame} = require('electron');
contextBridge.exposeInMainWorld('taskit', {
  load: () => ipcRenderer.invoke('load'),
  save: state => ipcRenderer.invoke('save', state),
  compact: (value,point) => ipcRenderer.invoke('compact', value, point),
  collapseTarget: point => ipcRenderer.invoke('collapse-target',point),
  dragStart: () => ipcRenderer.invoke('drag-start'),
  dragEnd: () => ipcRenderer.invoke('drag-end'),
  addCover: () => ipcRenderer.invoke('add-cover'),
  settings: value => ipcRenderer.invoke('settings', value),
  quit: () => ipcRenderer.invoke('quit'),
  reminderQueue: () => ipcRenderer.invoke('reminder-queue'),
  reminderAction: (id,action) => ipcRenderer.invoke('reminder-action',id,action),
  onReminderQueue: callback => { const fn=(_,value)=>callback(value);ipcRenderer.on('reminder-queue',fn);return()=>ipcRenderer.removeListener('reminder-queue',fn); },
  onState: callback => { const fn=(_,value)=>callback(value);ipcRenderer.on('state',fn);return()=>ipcRenderer.removeListener('state',fn); },
  onWheel: callback => { const fn = (_, value) => callback(value); ipcRenderer.on('wheel', fn); return () => ipcRenderer.removeListener('wheel', fn); },
  onReminder: callback => { const fn = (_, task) => callback(task); ipcRenderer.on('reminder', fn); return () => ipcRenderer.removeListener('reminder', fn); },
  onExpand: callback => { const fn = (_, value) => callback(value); ipcRenderer.on('expand', fn); return () => ipcRenderer.removeListener('expand', fn); }
});
